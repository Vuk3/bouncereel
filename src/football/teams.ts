/** A pool's sides; '' or an unknown pool is every one of the mode. */
export function poolSides(mode: Mode, pool: string): Side[] {
  const all = sidesOf(mode);
  if (pool === 'all' || pool === 'derbies') return all;
  const some = all.filter((s) => s.groups.includes(pool));
  return some.length >= 2 ? some : all;
}

/** The label the search shows beside a side: its league or country, or stars / legends. */
export function groupLabel(s: Side): string {
  if (s.mode === 'players') return `${s.groups.includes('legends') ? 'Legend' : 'Star'} · ${nationName(s)}`;
  const league: Record<string, string> = { england: 'Premier League', spain: 'La Liga', italy: 'Serie A', germany: 'Bundesliga', france: 'Ligue 1' };
  const first = s.groups.find((g) => g in league);
  return first ? league[first] : (country(s.nation)?.name ?? '');
}
