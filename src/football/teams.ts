const BY_ID = new Map(SIDES.map((s) => [s.id, s]));

export function side(id: string): Side | undefined {
  return BY_ID.get(id);
}

/** A side's name as the narrator says it, or its id when the list no longer has it (a config from elsewhere). */
export function sideName(id: string): string {
  return BY_ID.get(id)?.name ?? id;
}

/** Every club, or every player. */
export function sidesOf(mode: Mode): Side[] {
  return SIDES.filter((s) => s.mode === mode);
}

/** The derby or the rivalry the two make, as the narrator says it ("the Eternal Derby"); null for none. */
export function derby(a: string, b: string): string | null {
  return DERBIES.find(([x, y]) => (x === a && y === b) || (x === b && y === a))?.[2] ?? null;
}

/** Every derby of `mode`, as pairs: the dice's Derbies. */
export function derbies(mode: Mode): [string, string][] {
  return DERBIES.filter(([a]) => side(a)?.mode === mode).map(([a, b]) => [a, b]);
}

/** A national team as the narrator names it: the player's own (`team`), or his flag's country. */
export function nationName(s: Side): string {
  return s.team ?? country(s.nation)?.name ?? s.nation.toUpperCase();
}

