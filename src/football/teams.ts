// Goal Rush's sides: football clubs and football players. A match is two of one kind, picked in
// the studio (`match.mode`), drawn as a ball in their kit: a club in its own shirt's colours and
// pattern with its three letters on a roundel, a player in his national team's with his number
// (or his name, where no one number is his) and his name under it. Neither is a crest nor a photo:
// both are drawn here from colours, so nothing on the video is anyone's logo or picture.
//
// What the narrator says comes from here too (src/audio/narration.ts matchScript): a club's
// founding year and country, a derby's name; a player's birth year and national team. Only
// years and names, which never go out of date. A club's league is the one it played in in
// 2025/26 and only groups the dice and the search; nothing on screen says it.
//
// Names are as an English commentator says them ("Bayern Munich", "Wolves"); `short` is what the
// scoreboard and the winner card write, in capitals; `code` is the three or four letters on the
// ball. The search (src/ui/picker.ts) also matches `keys`: nicknames and local names ("zvezda",
// "barca", "cr7").

/** How a shirt is cut: what is drawn over its first colour in its second. */
export type Pattern = 'solid' | 'stripes' | 'hoops' | 'halves' | 'sash' | 'band' | 'bar' | 'sleeves' | 'checks' | 'diagonal';

export interface Kit {
  /** The shirt's colour and the one its pattern, roundel ring and collar are in. */
  colors: [string, string];
  pattern: Pattern;
  /**
   * The side's colour on the black stage: its ring, glow, trail and name. Its shirt's first colour
   * unless that is too dark to show (Juventus's black) or set here (France's navy reads as black).
   */
  glow?: string;
}

export type { Mode };

/** The dice's and the search's groups; a club or player may be in several. */
export interface Side {
  id: string;
  mode: Mode;
  name: string;
  short: string;
  /** On the ball: a club's three or four letters; a player's shirt number, or '' for his name. */
  mark: string;
  kit: Kit;
  /** The flag code of the club's country or the player's national team (src/battle/countries.ts). */
  nation: string;
  /** A club's founding year, a player's birth year; null where the year is in dispute. */
  year: number | null;
  /** What the dice can pick it from (CLUB_POOLS, PLAYER_POOLS), and the search's group label. */
  groups: string[];
  /** Nicknames and local names the search matches. */
  keys: string[];
  /** A player's position, for the narrator's fact. */
  position?: 'GK' | 'DF' | 'MF' | 'FW';
  /** A player's national team as the narrator says it, when it is not his flag's country ("the Soviet Union"). */
  team?: string;
}

